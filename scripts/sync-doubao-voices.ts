import { createHash, createHmac } from "node:crypto";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import type { VolcengineTtsVoice } from "../src/shared/audio.js";

// Refreshes src/shared/doubao-voices.ts from the official ListSpeakers API so
// the shipped catalog carries every Doubao Speech 2.0 preset voice and its
// official sample (TrialURL). ListSpeakers is an OpenAPI action signed with a
// Volcengine AccessKey, not the speech API key users enter in Settings, so it
// runs here instead of in the app:
//
//   VOLCENGINE_ACCESS_KEY_ID=... VOLCENGINE_SECRET_ACCESS_KEY=... bun run voices:doubao
//
// Dialect and voice-instruction support are not returned by the API; they are
// kept from the current catalog, which follows the published voice list.

const HOST = "open.volcengineapi.com";
const SERVICE = "speech_saas_prod";
const VERSION = "2025-05-20";
const PAGE_SIZE = 100;
const repositoryRoot = path.resolve(import.meta.dirname, "..");
const output = path.join(repositoryRoot, "src", "shared", "doubao-voices.ts");

const LANGUAGE_PREFIXES: Readonly<Record<string, string>> = {
  zh: "zh-cn", en: "en", ja: "ja", ko: "ko", id: "id", vi: "vi", th: "th", ms: "ms", it: "it",
  de: "de", fr: "fr", ru: "ru", ar: "ar", es: "es-es", mx: "es-mx", pt: "pt-br", tl: "fil",
};

/** Voice IDs start with their language; the published list uses the same mapping. */
export function voiceLanguage(id: string): string | undefined {
  return LANGUAGE_PREFIXES[id.slice(0, id.indexOf("_"))];
}

interface Speaker {
  VoiceType?: unknown;
  Name?: unknown;
  TrialURL?: unknown;
  ResourceID?: unknown;
}

/** Volcengine OpenAPI signature (HMAC-SHA256 over the canonical request). */
export function signVolcengineRequest(input: {
  accessKeyId: string;
  secretAccessKey: string;
  region: string;
  query: string;
  body: string;
  date: Date;
}): Record<string, string> {
  const xDate = input.date.toISOString().replace(/[-:]/g, "").replace(/\.\d{3}/, "");
  const day = xDate.slice(0, 8);
  const sha256 = (value: string) => createHash("sha256").update(value).digest("hex");
  const hmac = (key: string | Buffer, value: string) => createHmac("sha256", key).update(value).digest();
  const payloadHash = sha256(input.body);
  const signedHeaders = "host;x-content-sha256;x-date";
  const canonicalRequest = ["POST", "/", input.query, `host:${HOST}\nx-content-sha256:${payloadHash}\nx-date:${xDate}\n`, signedHeaders, payloadHash].join("\n");
  const scope = `${day}/${input.region}/${SERVICE}/request`;
  const signingKey = hmac(hmac(hmac(hmac(input.secretAccessKey, day), input.region), SERVICE), "request");
  const signature = createHmac("sha256", signingKey).update(["HMAC-SHA256", xDate, scope, sha256(canonicalRequest)].join("\n")).digest("hex");
  return {
    "Content-Type": "application/json",
    "X-Date": xDate,
    "X-Content-Sha256": payloadHash,
    Authorization: `HMAC-SHA256 Credential=${input.accessKeyId}/${scope}, SignedHeaders=${signedHeaders}, Signature=${signature}`,
  };
}

export function renderVoiceCatalog(voices: readonly VolcengineTtsVoice[]): string {
  const entries = voices.map((voice) => `  { ${Object.entries(voice).map(([key, value]) => `${key}: ${JSON.stringify(value)}`).join(", ")} },`);
  return [
    "// Generated by scripts/sync-doubao-voices.ts (`bun run voices:doubao`) from the",
    "// official Doubao Speech 2.0 voice list. Edit the script, not this file.",
    'import type { VolcengineTtsVoice } from "./audio.js";',
    "",
    "export const VOLCENGINE_TTS_VOICES: readonly VolcengineTtsVoice[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

/** Keeps known flags, takes names and samples from the API, and appends new voices. */
export function mergeVoiceCatalog(current: readonly VolcengineTtsVoice[], speakers: readonly Speaker[]): VolcengineTtsVoice[] {
  const known = new Map(current.map((voice) => [voice.id, voice]));
  const listed = new Map<string, VolcengineTtsVoice>();
  for (const speaker of speakers) {
    if (typeof speaker.VoiceType !== "string" || !speaker.VoiceType.endsWith("_uranus_bigtts")) continue;
    const id = speaker.VoiceType, language = voiceLanguage(id), previous = known.get(id);
    if (!language || listed.has(id)) continue;
    const name = typeof speaker.Name === "string" && speaker.Name.trim() ? speaker.Name.trim().replace(/\s*2\.0$/, "") : previous?.name ?? id;
    const trialUrl = typeof speaker.TrialURL === "string" && speaker.TrialURL.startsWith("https://") ? speaker.TrialURL : undefined;
    listed.set(id, {
      id,
      name,
      gender: id.includes("_female_") ? "female" : "male",
      language,
      ...(previous?.dialects ? { dialects: true as const } : {}),
      ...(previous?.noInstructions ? { noInstructions: true as const } : {}),
      ...(trialUrl ? { trialUrl } : {}),
    });
  }
  // Keep the current order and any voice the account did not list; append new voices.
  return [...current.map((voice) => listed.get(voice.id) ?? voice), ...[...listed.values()].filter((voice) => !known.has(voice.id))];
}

async function listSpeakers(accessKeyId: string, secretAccessKey: string, region: string): Promise<Speaker[]> {
  const speakers: Speaker[] = [];
  const query = `Action=ListSpeakers&Version=${VERSION}`;
  for (let page = 1; ; page += 1) {
    const body = JSON.stringify({ ResourceIDs: ["seed-tts-2.0"], Page: page, Limit: PAGE_SIZE });
    const response = await fetch(`https://${HOST}/?${query}`, {
      method: "POST",
      headers: signVolcengineRequest({ accessKeyId, secretAccessKey, region, query, body, date: new Date() }),
      body,
    });
    const result = (await response.json()) as { ResponseMetadata?: { Error?: { Code?: string; Message?: string } }; Result?: { Total?: number; Speakers?: Speaker[] } };
    const error = result.ResponseMetadata?.Error;
    if (!response.ok || error) throw new Error(`ListSpeakers failed (${response.status}): ${error?.Code ?? ""} ${error?.Message ?? ""}`.trim());
    const items = result.Result?.Speakers ?? [];
    speakers.push(...items);
    if (!items.length || speakers.length >= (result.Result?.Total ?? 0)) return speakers;
  }
}

async function main(): Promise<void> {
  const accessKeyId = process.env.VOLCENGINE_ACCESS_KEY_ID, secretAccessKey = process.env.VOLCENGINE_SECRET_ACCESS_KEY;
  if (!accessKeyId || !secretAccessKey) throw new Error("Set VOLCENGINE_ACCESS_KEY_ID and VOLCENGINE_SECRET_ACCESS_KEY");
  const { VOLCENGINE_TTS_VOICES } = await import("../src/shared/doubao-voices.js");
  const speakers = await listSpeakers(accessKeyId, secretAccessKey, process.env.VOLCENGINE_REGION ?? "cn-beijing");
  const voices = mergeVoiceCatalog(VOLCENGINE_TTS_VOICES, speakers);
  await writeFile(output, renderVoiceCatalog(voices));
  console.log(`Wrote ${voices.length} voices (${voices.filter((voice) => voice.trialUrl).length} with official samples) to ${path.relative(repositoryRoot, output)}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
