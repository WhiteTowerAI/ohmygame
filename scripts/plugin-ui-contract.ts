// Writes the page components' public contract, for each major version: a
// Custom Elements Manifest (custom-elements.json, schema 2.1.0) and
// TypeScript declarations (index.d.ts), both from the tags in each
// component's doc comment in packages/plugin-ui/ui/<major>/.
//
//   @attr {type} name - description         an attribute
//   @prop {type} name - description         a property
//   @method {signature} name - description  a method
//   @fires {detail} name - description      an event; without a detail, a plain Event
//   @slot name - description                a slot; `@slot - …` is the default slot
//   @part name - description                a `::part()`
//   @cssprop [--name=default] - description a CSS custom property
//   @deprecated what to use instead         the component is deprecated
//
// With --check, fails when the committed files are out of date. With
// --base <git ref>, also compares each major's contract with the one at that
// ref, and fails on a breaking change to a stable major: those wait for the
// next major. A major in preview may break; its changes are only listed.
import { execFileSync } from "node:child_process";
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PLUGIN_UI_MAJORS, PLUGIN_UI_PREVIEW_MAJORS } from "../src/shared/plugin-ui-versions.js";

const PACKAGE = path.join(path.dirname(fileURLToPath(import.meta.url)), "../packages/plugin-ui");
const GENERATED = "Generated by scripts/plugin-ui-contract.ts from the components' doc comments; run `bun run plugin-ui:contract` after changing them.";

interface Named {
  name: string;
  description?: string;
}
interface Typed extends Named {
  type?: { text: string };
}
interface CssProperty extends Named {
  default?: string;
}
interface Member extends Typed {
  kind: "field" | "method";
  inheritedFrom?: { name: string; module: string };
}
interface Declaration {
  kind: "class";
  name: string;
  tagName: string;
  customElement: true;
  description: string;
  deprecated?: string;
  superclass?: { name: string; module?: string; package?: string };
  attributes: (Typed & { inheritedFrom?: Member["inheritedFrom"] })[];
  members: Member[];
  events: (Typed & { inheritedFrom?: Member["inheritedFrom"] })[];
  slots: Named[];
  cssParts: Named[];
  cssProperties: CssProperty[];
}
interface Module {
  kind: "javascript-module";
  path: string;
  declarations: Declaration[];
  exports: { kind: "custom-element-definition"; name: string; declaration: { name: string; module: string } }[];
}
export interface ComponentManifest {
  schemaVersion: "2.1.0";
  readme: string;
  modules: Module[];
}

interface Parsed {
  name: string;
  superclass: string;
  module: string;
  description: string;
  deprecated?: string;
  attributes: Typed[];
  members: Member[];
  events: Typed[];
  slots: Named[];
  cssParts: Named[];
  cssProperties: CssProperty[];
}

const DOC_CLASS = /\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*class\s+(\w+)\s+extends\s+(\w+)/g;
const DEFINE = /define\("([a-z][a-z0-9-]*)",\s*(\w+)\)/g;

/** A tag's `{type}`, which may hold braces of its own. */
function takeType(text: string): [string | undefined, string] {
  if (!text.startsWith("{")) return [undefined, text];
  let depth = 0;
  for (let index = 0; index < text.length; index++) {
    if (text[index] === "{") depth++;
    else if (text[index] === "}" && --depth === 0) return [text.slice(1, index).trim(), text.slice(index + 1).trim()];
  }
  throw new Error(`Unclosed type in "${text}"`);
}

/** A tag's name and its description after ` - `. */
function takeName(text: string): [string, string | undefined] {
  const match = /^(\S*)\s*(?:-\s*([\s\S]*))?$/.exec(text.trim());
  if (!match) throw new Error(`Can't read "${text}"`);
  if (match[1] === "-") return ["", text.trim().slice(1).trim() || undefined];
  return [match[1]!, match[2]?.trim() || undefined];
}

function parseComment(comment: string, name: string, superclass: string, module: string): Parsed {
  const lines = comment
    .split("\n")
    .map((line) => line.replace(/^\s*\*\s?/, ""))
    .join("\n")
    .trim();
  const blocks = lines.split(/\n(?=@)/);
  const description = blocks[0]?.startsWith("@") ? "" : (blocks.shift() ?? "");
  const parsed: Parsed = { name, superclass, module, description: description.replace(/\s+/g, " ").trim(), attributes: [], members: [], events: [], slots: [], cssParts: [], cssProperties: [] };
  for (const raw of blocks) {
    const tag = raw.replace(/\s+/g, " ").trim();
    const [, kind = "", rest = ""] = /^@(\w+)\s*([\s\S]*)$/.exec(tag) ?? [];
    const [type, afterType] = takeType(rest);
    const [tagName, text] = takeName(afterType);
    if (kind !== "slot" && kind !== "deprecated" && !tagName) throw new Error(`${name}: @${kind} has no name`);
    const entry = { name: tagName, ...(text ? { description: text } : {}) };
    switch (kind) {
      case "attr":
        parsed.attributes.push({ ...entry, ...(type ? { type: { text: type } } : {}) });
        break;
      case "prop":
        parsed.members.push({ kind: "field", ...entry, ...(type ? { type: { text: type } } : {}) });
        break;
      case "method":
        parsed.members.push({ kind: "method", ...entry, ...(type ? { type: { text: type } } : {}) });
        break;
      case "fires":
        parsed.events.push({ ...entry, type: { text: type ? `CustomEvent<${type}>` : "Event" } });
        break;
      case "slot":
        parsed.slots.push(entry);
        break;
      case "part":
        parsed.cssParts.push(entry);
        break;
      case "cssprop": {
        const [, property, value] = /^\[?(--[\w-]+)(?:=([^\]]*))?\]?$/.exec(tagName) ?? [];
        if (!property) throw new Error(`${name}: "${tagName}" isn't a CSS custom property`);
        parsed.cssProperties.push({ name: property, ...(value ? { default: value } : {}), ...(text ? { description: text } : {}) });
        break;
      }
      case "deprecated":
        parsed.deprecated = rest.trim() || "Deprecated.";
        break;
      default:
        throw new Error(`${name}: unknown tag @${kind}`);
    }
  }
  return parsed;
}

const byName = <T extends Named>(items: T[]) => [...items].sort((a, b) => a.name.localeCompare(b.name));

/** One major's contract, read from its components' sources. */
export async function componentManifest(major: string): Promise<ComponentManifest> {
  const directory = path.join(PACKAGE, "ui", major);
  const files = (await readdir(directory)).filter((file) => file.endsWith(".js")).sort();
  const classes = new Map<string, Parsed>();
  const definitions: { tag: string; name: string; module: string }[] = [];
  for (const file of files) {
    const module = `ui/${major}/${file}`;
    const source = await readFile(path.join(directory, file), "utf8");
    for (const [, comment, name, superclass] of source.matchAll(DOC_CLASS)) classes.set(name!, parseComment(comment!, name!, superclass!, module));
    for (const [, tag, name] of source.matchAll(DEFINE)) definitions.push({ tag: tag!, name: name!, module });
  }
  const modules = new Map<string, Module>();
  for (const { tag, name, module } of definitions) {
    const own = classes.get(name);
    if (!own) throw new Error(`${tag}: its class ${name} has no doc comment`);
    // A component inherits what its superclass offers, as the manifest records.
    const chain: Parsed[] = [];
    for (let current: Parsed | undefined = own; current; current = classes.get(current.superclass)) chain.push(current);
    const inherited = <T extends Named>(pick: (item: Parsed) => T[], mark: boolean) => {
      const seen = new Map<string, T>();
      for (const item of chain)
        for (const entry of pick(item))
          if (!seen.has(entry.name)) seen.set(entry.name, item === own || !mark ? entry : { ...entry, inheritedFrom: { name: item.name, module: item.module } });
      return byName([...seen.values()]);
    };
    const parent = classes.get(own.superclass);
    const declaration: Declaration = {
      kind: "class",
      name,
      tagName: tag,
      customElement: true,
      description: own.description,
      ...(own.deprecated ? { deprecated: own.deprecated } : {}),
      superclass: parent ? { name: parent.name, module: parent.module } : { name: "HTMLElement", package: "global:" },
      attributes: inherited((item) => item.attributes, true),
      members: inherited((item) => item.members, true),
      events: inherited((item) => item.events, true),
      slots: inherited((item) => item.slots, false),
      cssParts: inherited((item) => item.cssParts, false),
      cssProperties: inherited((item) => item.cssProperties, false),
    };
    const entry = modules.get(module) ?? { kind: "javascript-module" as const, path: module, declarations: [], exports: [] };
    entry.declarations.push(declaration);
    entry.exports.push({ kind: "custom-element-definition", name: tag, declaration: { name, module } });
    modules.set(module, entry);
  }
  return { schemaVersion: "2.1.0", readme: "", modules: [...modules.values()].sort((a, b) => a.path.localeCompare(b.path)) };
}

export const declarations = (manifest: ComponentManifest) => manifest.modules.flatMap((module) => module.declarations);

const BOOLEAN = "boolean";
const doc = (text: string | undefined, indent: string, deprecated?: string) =>
  text || deprecated ? `${indent}/** ${[text, deprecated ? `@deprecated ${deprecated}` : ""].filter(Boolean).join(" ")} */\n` : "";
const key = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

/** TypeScript declarations for one major's components. */
export function componentTypes(manifest: ComponentManifest): string {
  const all = declarations(manifest);
  const names = new Set(all.map((item) => item.name));
  const element = (name: string) => `${name}Element`;
  let out = `// ${GENERATED}\n\n`;
  for (const item of all) {
    const parent = item.superclass?.name && names.has(item.superclass.name) ? element(item.superclass.name) : "HTMLElement";
    out += doc(item.description, "", item.deprecated);
    const members = item.members.filter((entry) => !entry.inheritedFrom);
    out += `export interface ${element(item.name)} extends ${parent} {${members.length ? "\n" : ""}`;
    for (const member of members) out += doc(member.description, "  ") + `  ${key(member.name)}: ${member.type?.text ?? (member.kind === "method" ? "() => void" : "unknown")};\n`;
    out += "}\n\n";
    out += `/** The attributes of \`<${item.tagName}>\`, as a page writes them. */\n`;
    out += `export interface ${item.name}Attributes {\n`;
    for (const attribute of item.attributes) {
      out += doc(attribute.description, "  ");
      const type = attribute.type?.text ?? "string";
      out += `  ${key(attribute.name)}?: ${type === BOOLEAN ? "boolean" : type};\n`;
    }
    out += "}\n\n";
  }
  const events = all.flatMap((item) => item.events.filter((event) => !event.inheritedFrom && event.type?.text !== "Event"));
  out += "declare global {\n  interface HTMLElementTagNameMap {\n";
  for (const item of all) out += `    ${JSON.stringify(item.tagName)}: ${element(item.name)};\n`;
  out += "  }\n";
  if (events.length) {
    out += "  interface HTMLElementEventMap {\n";
    for (const event of events) out += doc(event.description, "    ") + `    ${JSON.stringify(event.name)}: ${event.type!.text};\n`;
    out += "  }\n";
  }
  out += "}\n";
  return out;
}

type Kind = "attributes" | "members" | "events" | "slots" | "cssParts" | "cssProperties";
const KINDS: Record<Kind, string> = { attributes: "attribute", members: "member", events: "event", slots: "slot", cssParts: "part", cssProperties: "CSS property" };

/** A union of string literals, or undefined for any other type. */
function literals(type: string | undefined): Set<string> | undefined {
  if (!type) return undefined;
  const values = type.split("|").map((part) => part.trim());
  return values.every((value) => /^"[^"]*"$/.test(value)) ? new Set(values) : undefined;
}

/**
 * What changed between two versions of a contract. A removal, or a type
 * that changed, breaks pages; an attribute whose values only grew doesn't.
 */
export function contractChanges(before: ComponentManifest, after: ComponentManifest): { breaking: string[]; added: string[] } {
  const breaking: string[] = [];
  const added: string[] = [];
  const now = new Map(declarations(after).map((item) => [item.tagName, item]));
  const then = new Map(declarations(before).map((item) => [item.tagName, item]));
  for (const [tag, old] of then) {
    const current = now.get(tag);
    if (!current) {
      breaking.push(`<${tag}> was removed`);
      continue;
    }
    for (const kind of Object.keys(KINDS) as Kind[]) {
      const items = new Map<string, Typed>((current[kind] as Typed[]).map((item) => [item.name, item]));
      for (const item of old[kind] as Typed[]) {
        const label = `<${tag}> ${KINDS[kind]} ${item.name || "(default slot)"}`;
        const next = items.get(item.name);
        if (!next) breaking.push(`${label} was removed`);
        else if (item.type?.text !== next.type?.text) {
          const was = literals(item.type?.text);
          const is = literals(next.type?.text);
          if (kind === "attributes" && was && is && [...was].every((value) => is.has(value))) added.push(`${label} takes ${[...is].filter((value) => !was.has(value)).join(", ")}`);
          else breaking.push(`${label} changed from ${item.type?.text ?? "untyped"} to ${next.type?.text ?? "untyped"}`);
        }
        items.delete(item.name);
      }
      for (const item of items.values()) added.push(`<${tag}> ${KINDS[kind]} ${item.name || "(default slot)"}`);
    }
  }
  for (const tag of now.keys()) if (!then.has(tag)) added.push(`<${tag}>`);
  return { breaking, added };
}

const manifestFile = (major: string) => path.join(PACKAGE, "ui", major, "custom-elements.json");
const typesFile = (major: string) => path.join(PACKAGE, "ui", major, "index.d.ts");
export const contractJson = (manifest: ComponentManifest) => `${JSON.stringify(manifest, null, 2)}\n`;

/** The files each major's contract writes, with their expected text. */
export async function contractFiles(): Promise<{ file: string; text: string }[]> {
  const files = [];
  for (const major of PLUGIN_UI_MAJORS) {
    const manifest = await componentManifest(major);
    files.push({ file: manifestFile(major), text: contractJson(manifest) }, { file: typesFile(major), text: componentTypes(manifest) });
  }
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const baseIndex = process.argv.indexOf("--base");
  const base = baseIndex === -1 ? undefined : process.argv[baseIndex + 1];
  let failed = false;
  for (const { file, text } of await contractFiles()) {
    const relative = path.relative(process.cwd(), file);
    if (!check) await writeFile(file, text);
    else if ((await readFile(file, "utf8").catch(() => "")) !== text) {
      console.error(`${relative} is out of date; run bun run plugin-ui:contract`);
      failed = true;
    }
  }
  if (base) {
    for (const major of PLUGIN_UI_MAJORS) {
      let previous: string;
      try {
        previous = execFileSync("git", ["show", `${base}:packages/plugin-ui/ui/${major}/custom-elements.json`], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
      } catch {
        console.log(`Components ${major}: new since ${base}.`);
        continue;
      }
      const { breaking, added } = contractChanges(JSON.parse(previous) as ComponentManifest, await componentManifest(major));
      const preview = PLUGIN_UI_PREVIEW_MAJORS.has(major);
      for (const change of added) console.log(`Components ${major}: added ${change}`);
      for (const change of breaking) (preview ? console.log : console.error)(`Components ${major}${preview ? " (preview)" : ""}: ${change}`);
      if (breaking.length && !preview) {
        console.error(`Components ${major} are stable: a breaking change waits for the next major. See docs/plugins.md#page-components.`);
        failed = true;
      }
    }
  }
  if (failed) process.exit(1);
}
